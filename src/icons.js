/** Insere o SVG correspondente em todo elemento com data-icon (antes do texto). */
export function renderIcons(root = document) {
  root.querySelectorAll("[data-icon]:not([data-icon-done])").forEach((node) => {
    node.insertAdjacentHTML("afterbegin", icon(node.dataset.icon));
    node.dataset.iconDone = "";
  });
}
